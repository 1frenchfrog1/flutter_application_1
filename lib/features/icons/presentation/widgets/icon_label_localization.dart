/// Label of [icon] in [languageCode]; falls back to the catalog label (French).
String localizeIconLabel(IconEntity icon, String languageCode) {
  final catalogLabel = icon.label ?? icon.key;
  final translated = _cookingIconLabels[icon.key] ?? generalIconLabels[icon.key];
  if (translated == null) return catalogLabel;
  return switch (languageCode) {
    'fr' => catalogLabel,
    'de' => translated.$2,
    'es' => translated.$3,
    'it' => translated.$4,
    _ => translated.$1,
  };
}
